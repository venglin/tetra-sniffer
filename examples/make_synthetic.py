"""Generate examples/synthetic.cs8: two fictitious TETRA cells in a 576 ksps capture.

The cells use MCC 901 (shared international code) and carriers around 490 MHz,
outside the bands used by TETRA, so the file cannot be mistaken for a real network.

    python examples/make_synthetic.py
    tetrascan file examples/synthetic.cs8
"""

from pathlib import Path

from tetrascan import sim

FS = 576e3
CENTER = 490.2e6

cell_a = sim.CellConfig(mcc=901, mnc=9999, cc=17, la=1001, main_carrier=3612)  # 490.3000 MHz
cell_b = sim.CellConfig(mcc=901, mnc=9999, cc=42, la=1002, main_carrier=3602, group=2345678,
                        ms=8765432)  # 490.0500 MHz

x = sim.wideband([(cell_a.main_carrier * 25e3 + 400e6 - CENTER, cell_a, 0.0),
                  (cell_b.main_carrier * 25e3 + 400e6 - CENTER, cell_b, -6.0)],
                 FS, duration_s=2.5, snr_db=22.0, ppm=12.0, seed=7)
out = Path(__file__).with_name("synthetic.cs8")
sim.write_cs8(out, x, FS, CENTER, note="synthetic test signal generated by examples/make_synthetic.py")
print(f"wrote {out} ({len(x)} samples)")
